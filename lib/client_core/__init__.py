"""Клиентское ЯДРО Friend Relay — логика приложения без Qt.

Сюда переезжает то, что раньше жило внутри qt_app-экранов и диалогов:
политики поллинга, диффы лент, состояния сессий, правила. Ядро НЕ знает
ни про QWidget, ни про сигналы — экраны подписываются на обычные
колбэки и занимаются только отрисовкой.

Слои теперь такие (сверху вниз):

    qt_app/            — View: виджеты, раскладка, мост колбэков в GUI-поток
    lib/client_core/   — ЯДРО: «что происходит» (этот пакет)
    lib/client.py      — Транспорт клиента: HTTP-функции без состояния UI
    lib/server/*       — Транспорт сервера: http_api → relay_server → domain

Правило слоёв: ядро может импортировать lib (client, constants), но НЕ
qt_app. Обратное тоже полезно держать: qt_app импортирует ядро, но не
дублирует его логику.

Модули:
    chat_session.py — ядро экрана чата: поллинг, каналы, типинг (Фаза 1)
    chess_match.py  — ядро шахматного диалога: результат, сетевой матч,
                      рейтинг ELO (Фаза 2)
    social.py       — профиль/друзья/файлы/DM: рендер статистики, фильтры
                      витрины, группировка ЛС (Фаза 3)
"""
