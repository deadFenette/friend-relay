"""Константы модуля стриминга экрана (screen/) — единое место тюнинга.

По образцу voice/config.py: ничего не вычисляется, только честные числа
с пояснениями. Сервер медиа НЕ качает (WebRTC P2P), поэтому констант
немного: это лимиты сигналинг-почты и живость реестра показов.
"""
from __future__ import annotations

# ── живость реестра показов ──────────────────────────────────────────────
# Ведущий раз в ~8с шлёт heartbeat (POST /screen/publish on=true). Показ
# считается живым, если heartbeat был не позднее STREAM_LIVE_S назад.
# Хост, у которого закрылась вкладка без «закончить показ», сам исчезнет
# из списка через это время — фонового потока-уборщика не нужно, чистим
# лениво при каждом обращении.
STREAM_LIVE_S = 30.0

# ── живость зрителя в счётчике «смотрят» ─────────────────────────────────
# (v3.6.3) Зритель, чья вкладка умерла без «bye», раньше оставался в
# счётчике до конца показа. Теперь watch(on=true) — это ещё и пульс:
# клиент повторяет его раз в ~12с (SCREEN_WATCH_BEAT_MS в screen.js), а
# хаб считает зрителя живым, только если пульс был не позднее
# WATCHER_STALE_S назад (3 пропущенных пульса). WebRTC-поток это не
# трогает (медиа идёт P2P мимо сервера) — точность счётчика в /screen/info.
WATCHER_STALE_S = 40.0

# ── сигналинг-почта (offer/answer/bye) ───────────────────────────────────
# Сколько хранить неотданное сообщение на получателя. ICE-сборка с
# таймаутом занимает ~1.5с, ответ медленного зрителя — секунды, поэтому
# запас большой; всё, что старше, зритель уже не возьмёт.
SIGNAL_TTL_S = 90.0

# Максимум НЕзабранных сообщений на одного получателя. Живой зритель
# забирает почту раз в ~1.5с; 256 сообщений — это минуты офлайна и
# одновременные рестарты показа у нескольких ведущих.
MAILBOX_MAX = 256

# Максимум РАЗМЕРА одного сигнала. Полный SDP с ICE-кандидатами —
# единицы-десятки КБ; лимит отсекает только абьюз (MAX_JSON_BODY у
# HTTP-слоя 2 МБ, но сигнал живёт в RAM на получателя — держим жёстче).
MAX_SIGNAL_BYTES = 256 * 1024
